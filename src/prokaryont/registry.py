def get_registry_summary() -> dict[str, int]:
    """Berechnet die exakte Anzahl nach Kategorie und Status für Audits."""
    prokaryote_items = [s for s in STRUCTURE_REGISTRY if s.category == "prokaryote"]
    viability_items = [s for s in STRUCTURE_REGISTRY if s.category == "viability"]
    return {
        "total_all": len(STRUCTURE_REGISTRY),
        "prokaryote_total": len(prokaryote_items),
        "prokaryote_active": sum(1 for s in prokaryote_items if s.status == "active"),
        "prokaryote_submodule": sum(1 for s in prokaryote_items if s.status == "submodule"),
        "prokaryote_implemented": sum(
            1 for s in prokaryote_items if s.status in ("active", "submodule")
        ),
        "prokaryote_merged": sum(1 for s in prokaryote_items if s.status == "merged"),
        "prokaryote_excluded": sum(1 for s in prokaryote_items if s.status == "excluded"),
        "viability_total": len(viability_items),
    }


